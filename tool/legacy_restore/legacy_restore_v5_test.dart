class _Paths extends PathProviderPlatform {
  _Paths(this.root);
  final String root;
  @override
  Future<String?> getApplicationSupportPath() async => root;
  @override
  Future<String?> getApplicationDocumentsPath() async => root;
  @override
  Future<String?> getApplicationCachePath() async => '$root/cache';
  @override
  Future<String?> getTemporaryPath() async => '$root/tmp';
}

List<Map<String, Object?>> _rows(sqlite.Database db, String sql) =>
    db.select(sql).map((r) => Map<String, Object?>.from(r)).toList();
const _messages =
    'SELECT id, conversation_id, role, message_order, group_id, version '
    'FROM message_rows ORDER BY conversation_id, message_order, id;';
const _parts =
    'SELECT revision_id, ordinal, kind, payload FROM message_part_rows '
    'ORDER BY revision_id, ordinal;';
const _conversations =
    'SELECT id, title, version_selections_json FROM conversation_rows ORDER BY id;';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  test(
    'frozen v3 restores real v5 archive through preparation and startup cutover',
    () async {
      expect(AppDatabase.currentSchemaVersion, 3);
      expect(AppDatabase.publishedSchemaVersions, {1, 2, 3});
      const expectedRoot = String.fromEnvironment('GENUI_LEGACY_SOURCE_ROOT');
      expect(expectedRoot, isNotEmpty);
      final resolvedRoot = await Directory(expectedRoot).resolveSymbolicLinks();
      // Flutter's test runner does not implement Isolate.resolvePackageUri.
      // Read the configuration generated by pub in this frozen source root;
      // the imported production constants above independently prove v3 code.
      final packageConfig = File('.dart_tool/package_config.json').absolute;
      final packages =
          (jsonDecode(await packageConfig.readAsString()) as Map)['packages']
              as List;
      final package = packages.cast<Map>().singleWhere(
        (entry) => entry['name'] == 'Kelivo',
      );
      final packageUri = packageConfig.uri
          .resolve(package['rootUri'] as String)
          .resolve(package['packageUri'] as String)
          .resolve('core/database/app_database.dart');
      expect(
        p.isWithin(
          resolvedRoot,
          await File(packageUri.toFilePath()).resolveSymbolicLinks(),
        ),
        isTrue,
      );
      expect(await Directory.current.resolveSymbolicLinks(), resolvedRoot);

      final archiveFile = File('test/fixtures/genui-v5.zip').absolute;
      expect(await archiveFile.exists(), isTrue);
      final originalHash = (await sha256.bind(archiveFile.openRead()).first)
          .toString();
      final root = await Directory.systemTemp.createTemp('genui-legacy-app-');
      final previousPaths = PathProviderPlatform.instance;
      PathProviderPlatform.instance = _Paths(root.path);
      SandboxPathResolver.debugSetDirs(
        docsDir: root.path,
        supportDir: root.path,
      );
      SharedPreferences.setMockInitialValues({});
      ChatService? chat;
      ChatDatabaseLease? businessLease;
      ChatDatabaseRepository? reopened;
      try {
        final archive = ZipDecoder().decodeBytes(
          await archiveFile.readAsBytes(),
        );
        final manifest =
            jsonDecode(
                  utf8.decode(archive.findFile('manifest.json')!.readBytes()!),
                )
                as Map;
        expect(manifest['formatVersion'], 3);
        expect(manifest['minimumReadableFormatVersion'], 3);
        expect(manifest['database']['schemaVersion'], 5);
        expect(manifest['database']['minimumReadableSchemaVersion'], 2);
        final expectedDatabase = File(p.join(root.path, 'expected-v5.sqlite'));
        await expectedDatabase.writeAsBytes(
          archive.findFile('database/kelivo.db')!.readBytes()!,
        );
        archive.clear();
        final source = sqlite.sqlite3.open(
          expectedDatabase.path,
          mode: sqlite.OpenMode.readOnly,
        );
        late List<Map<String, Object?>> expectedMessages,
            expectedParts,
            expectedConversations;
        try {
          expect(source.userVersion, 5);
          expectedMessages = _rows(source, _messages);
          expectedParts = _rows(source, _parts);
          expectedConversations = _rows(source, _conversations);
          expect(expectedMessages.length, greaterThanOrEqualTo(3));
          expect(expectedMessages.any((m) => m['role'] == 'user'), isTrue);
          expect(
            expectedMessages.any((m) => (m['version'] as int) > 0),
            isTrue,
          );
          expect(
            expectedParts
                .where(
                  (p) =>
                      p['kind'] == 'text' &&
                      (p['payload'] as String).contains('```kelivo-ui'),
                )
                .length,
            greaterThanOrEqualTo(2),
          );
          final states = _rows(
            source,
            'SELECT state_json, search_text FROM gen_ui_surface_state_rows;',
          );
          expect(states.length, greaterThanOrEqualTo(2));
          expect(
            states.any(
              (s) => (jsonDecode(s['state_json'] as String)['inputs'] as Map)
                  .isNotEmpty,
            ),
            isTrue,
          );
          expect(
            states.any(
              (s) => (jsonDecode(s['state_json'] as String)['view'] as Map)
                  .isNotEmpty,
            ),
            isTrue,
          );
          expect(
            states.any((s) => (s['search_text'] as String).isNotEmpty),
            isTrue,
          );
        } finally {
          source.close();
        }

        final appData = await AppDirectories.getAppDataDirectory();
        expect(
          p.equals(appData.path, root.path) ||
              p.isWithin(root.path, appData.path),
          isTrue,
        );
        final databaseFile = File(
          p.join(appData.path, AppDatabase.databaseFileName),
        );
        final gateway = ChatDatabaseGateway();
        chat = ChatService(databaseGateway: gateway);
        await chat.init();
        businessLease = await gateway.acquire(databaseFile);
        final oldRepo = businessLease.chatRepository;
        await oldRepo.putConversation(
          Conversation(id: 'old-local', title: 'Before restore'),
        );
        final oldMessage = ChatMessage(
          id: 'old-local-message',
          conversationId: 'old-local',
          role: 'user',
          content: 'Replace me',
        );
        await oldRepo.putMessage(oldMessage);
        final preferences = BusinessPreferences(
          businessLease.businessRepository,
        );
        await preferences.load();
        final sync = DataSync(
          chatService: chat,
          businessRepository: businessLease.businessRepository,
          businessPreferences: preferences,
        );
        final compatibility = await DataSync.inspectBackupCompatibility(
          archiveFile,
        );
        expect(compatibility?.schemaVersion, 5);
        expect(compatibility?.verdict, BackupSchemaVerdict.forwardCompatible);
        await sync.restoreFromLocalFile(
          archiveFile,
          const WebDavConfig(),
          mode: RestoreMode.overwrite,
          onForwardCompatibility: (value) async {
            expect(value.verdict, BackupSchemaVerdict.forwardCompatible);
            return ForwardCompatibilityAnswer.proceed;
          },
        );
        // A prepared bundle is not a completed overwrite.
        expect(await oldRepo.getMessage(oldMessage.id), isNotNull);
        expect(
          await RestoreStartupGate.inspect(appDataDirectory: appData),
          isNotNull,
        );
        await chat.close();
        chat = null;
        await businessLease.release();
        businessLease = null;
        final recovered =
            await RestoreStartupGate.recoverAndRequireBusinessReady(
              appDataDirectory: appData,
            );
        expect(recovered?.state, RestoreReceiptState.committed);
        final info = await ChatDatabaseRepository.inspectPreparedSnapshot(
          databaseFile,
        );
        expect(info.schemaVersion, 3);
        expect(info.messageCount, expectedMessages.length);
        final restored = sqlite.sqlite3.open(
          databaseFile.path,
          mode: sqlite.OpenMode.readOnly,
        );
        try {
          expect(restored.userVersion, 3);
          expect(_rows(restored, _messages), expectedMessages);
          expect(_rows(restored, _parts), expectedParts);
          expect(_rows(restored, _conversations), expectedConversations);
          expect(
            restored.select(
              "SELECT name FROM sqlite_master WHERE name LIKE 'gen_ui_%';",
            ),
            isEmpty,
          );
          expect(restored.select('PRAGMA foreign_key_check;'), isEmpty);
        } finally {
          restored.close();
        }
        reopened = ChatDatabaseRepository.open(file: databaseFile);
        await reopened.ensureReady();
        await reopened.validateConnectionContract();
        await reopened.putConversation(
          Conversation(id: 'crud', title: 'Old reader writes'),
        );
        final crud = ChatMessage(
          id: 'crud-message',
          conversationId: 'crud',
          role: 'user',
          content: 'Old CRUD works',
        );
        await reopened.putMessage(crud);
        expect((await reopened.getMessage(crud.id))!.content, crud.content);
        await reopened.deleteConversation('crud');
        expect(await reopened.getMessage(crud.id), isNull);
        await reopened.close();
        reopened = null;
        expect(
          (await sha256.bind(archiveFile.openRead()).first).toString(),
          originalHash,
        );
      } finally {
        await reopened?.close();
        await chat?.close();
        await businessLease?.release();
        SandboxPathResolver.debugSetDirs(docsDir: null, supportDir: null);
        PathProviderPlatform.instance = previousPaths;
        await root.delete(recursive: true);
      }
    },
    timeout: const Timeout(Duration(minutes: 5)),
  );
}
