// An empty subLanguage list asks re_highlight to auto-detect against every
// registered grammar. Omit modes with no embedded languages from the index.
List<String>? embeddedLanguages(Mode root) {
  final visited = Set<Mode>.identity();
  final names = <String>{};
  var autoDetect = false;
  void visit(Object? value) {
    if (value is Mode && visited.add(value)) {
      final sub = value.subLanguage;
      if (sub is String) {
        names.add(sub);
      } else if (sub is List<String>) {
        autoDetect |= sub.isEmpty;
        names.addAll(sub);
      }
      visit(value.refs);
      visit(value.contains);
      visit(value.variants);
      visit(value.starts);
    } else if (value is Map) {
      visit(value.values);
    } else if (value is Iterable) {
      value.forEach(visit);
    }
  }

  visit(root);
  if (autoDetect) return const [];
  return names.isEmpty ? null : (names.toList()..sort());
}

// Run with flutter test tool/generate_highlight_languages.dart, then dart format.
void main() => test('generate lazy highlighter definitions', () async {
  final config = File('.dart_tool/package_config.json').absolute;
  final packages =
      jsonDecode(config.readAsStringSync()) as Map<String, dynamic>;
  final package = (packages['packages'] as List)
      .cast<Map<String, dynamic>>()
      .firstWhere((package) => package['name'] == 're_highlight');
  final allUri = config.uri
      .resolve('${package['rootUri']}/')
      .resolve('${package['packageUri']}languages/all.dart');
  final source = File.fromUri(allUri).readAsStringSync();
  final imports = RegExp(r"import '([^']+)';").allMatches(source);
  final definitions = <String, String>{};
  for (final match in imports) {
    final path = match[1]!;
    final contents = File.fromUri(allUri.resolve(path)).readAsStringSync();
    final name = RegExp(r'final (lang\w+) =').firstMatch(contents)![1]!;
    definitions[name] = path;
  }
  final symbols = <String, String>{
    for (final match in RegExp(r"'([^']+)': (lang\w+),").allMatches(source))
      match[1]!: match[2]!,
  };
  final names = {
    for (final key in builtinAllLanguages.keys) key: symbols[key]!,
  };
  final parser = Highlight()..registerLanguages(builtinAllLanguages);
  final aliases = <String, String>{};
  for (final entry in builtinAllLanguages.entries) {
    for (final alias in entry.value.aliases ?? <String>[]) {
      final language = parser.getLanguage(alias)!;
      aliases[alias.toLowerCase()] = builtinAllLanguages.entries
          .firstWhere((entry) => identical(entry.value, language))
          .key;
    }
  }
  final output = StringBuffer()
    ..writeln(
      '// Generated by tool/generate_highlight_languages.dart. Do not edit.',
    )
    ..writeln()
    ..writeln("import 'package:re_highlight/re_highlight.dart';");
  for (final entry in names.entries) {
    output.writeln(
      "import 'package:re_highlight/languages/${definitions[entry.value]}' as ${entry.value.toLowerCase()};",
    );
  }
  output
    ..writeln()
    ..writeln('final highlightLanguageFactories = <String, Mode Function()>{');
  for (final entry in names.entries) {
    output.writeln(
      "  '${entry.key}': () => ${entry.value.toLowerCase()}.${entry.value},",
    );
  }
  output
    ..writeln('};')
    ..writeln()
    ..writeln('const highlightLanguageAliases = <String, String>{');
  for (final entry in aliases.entries) {
    output.writeln("  '${entry.key}': '${entry.value}',");
  }
  output
    ..writeln('};')
    ..writeln()
    ..writeln('const highlightEmbeddedLanguages = <String, List<String>>{');
  for (final entry in builtinAllLanguages.entries) {
    final embedded = embeddedLanguages(entry.value);
    if (embedded != null) {
      output.writeln("  '${entry.key}': ${jsonEncode(embedded)},");
    }
  }
  output.writeln('};');
  File(
    'lib/shared/markdown/highlight_languages.g.dart',
  ).writeAsStringSync(output.toString());
});
