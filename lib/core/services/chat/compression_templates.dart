bool _usesChinesePrompts(String locale) =>
    locale.toLowerCase().split(RegExp('[-_]')).first == 'zh';

List<CompressionTemplate> builtInCompressionTemplatesForLocale(String locale) =>
    _usesChinesePrompts(locale)
    ? builtInCompressionTemplates
    : en.builtInCompressionTemplates;

String compressionContractForLocale(String locale, {bool legacy = false}) {
  final chinese = _usesChinesePrompts(locale);
  final contract = chinese ? compressionContract : en.compressionContract;
  if (!legacy) return contract;
  return contract.replaceFirst(
    chinese
        ? '指定了输出语言时遵循指定；否则跟随对话的主要语言。'
        : 'Follow the configured output language; otherwise use the main language of the conversation.',
    chinese
        ? '输出语言遵循原模板的要求；未指定时使用 $locale。'
        : 'Follow the output language specified by the original template; if unspecified, use $locale.',
  );
}

String compressionUpdateInstructionForLocale(String locale) =>
    _usesChinesePrompts(locale)
    ? compressionUpdateInstruction
    : en.compressionUpdateInstruction;

