String foldUnicodeScalar(int scalar) {
  if (scalar < 128) {
    return String.fromCharCode(
      scalar >= 65 && scalar <= 90 ? scalar + 32 : scalar,
    );
  }
  final expansion = _expansions[scalar];
  if (expansion != null) return expansion;
  var low = 0, high = _ranges.length;
  while (low < high) {
    final mid = (low + high) ~/ 2;
    final (start, end, stride, delta) = _ranges[mid];
    if (scalar < start) {
      high = mid;
    } else if (scalar > end) {
      low = mid + 1;
    } else {
      return String.fromCharCode(
        (scalar - start) % stride == 0 ? scalar + delta : scalar,
      );
    }
  }
  return String.fromCharCode(scalar);
}
